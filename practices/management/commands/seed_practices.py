class Command(BaseCommand):
    help = "Заполняет базовые карточки дыхательных практик"

    def handle(self, *args, **options):
        created_count = 0
        updated_count = 0

        for item in PRACTICES:
            _, created = BreathingPractice.objects.update_or_create(
                title=item["title"],
                defaults={
                    "description": item["description"],
                    "duration_minutes": item["duration_minutes"],
                    "cycles": item["cycles"],
                    "instruction": item["instruction"],
                    "is_active": True,
                },
            )

            if created:
                created_count += 1
            else:
                updated_count += 1

        self.stdout.write(
            self.style.SUCCESS(
                f"Практики обновлены. Создано: {created_count}, обновлено: {updated_count}."
            )
        )
